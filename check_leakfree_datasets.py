import json
from pathlib import Path

import numpy as np
import pandas as pd


DATASETS = [
    "ili_us_states_h4_leakfree",
    "ili_us_states_h8_leakfree",
    "ili_us_states_h12_leakfree",
    "us_states_nhsn_flu_hosp_h4_leakfree",
    "us_states_nhsn_flu_hosp_h8_leakfree",
    "us_states_nhsn_flu_hosp_h12_leakfree",
]


def package_dir(dataset_name):
    return Path("dataset") / dataset_name / dataset_name


def processed_dir(dataset_name):
    return Path("dataset") / dataset_name / "processed"


def load_npz(dataset_name, split):
    path = package_dir(dataset_name) / f"{split}.npz"
    if not path.exists():
        raise FileNotFoundError(path)
    return np.load(path)


def check_split(dataset_name, split):
    data = load_npz(dataset_name, split)
    required = ["x", "y", "x_mask", "y_mask", "week_idx_x", "week_idx_y"]
    missing = [name for name in required if name not in data]
    if missing:
        raise AssertionError(f"{dataset_name}/{split} missing fields: {missing}")

    x = data["x"]
    y = data["y"]
    x_mask = data["x_mask"]
    y_mask = data["y_mask"]
    if x.shape != x_mask.shape:
        raise AssertionError(f"{dataset_name}/{split} x shape {x.shape} != x_mask {x_mask.shape}")
    if y.shape != y_mask.shape:
        raise AssertionError(f"{dataset_name}/{split} y shape {y.shape} != y_mask {y_mask.shape}")
    if not np.isfinite(x).all():
        raise AssertionError(f"{dataset_name}/{split} x contains NaN/inf")
    if not np.isfinite(y).all():
        raise AssertionError(f"{dataset_name}/{split} y contains NaN/inf")

    return {
        "split": split,
        "x_shape": tuple(int(v) for v in x.shape),
        "y_shape": tuple(int(v) for v in y.shape),
        "x_missing": int((~x_mask.astype(bool)).sum()),
        "y_missing": int((~y_mask.astype(bool)).sum()),
    }


def check_scaler(dataset_name):
    meta_path = package_dir(dataset_name) / "meta.json"
    with open(meta_path, "r", encoding="utf-8") as f:
        meta = json.load(f)
    train = load_npz(dataset_name, "train")
    train_x = train["x"][..., 0]
    mean = float(train_x.mean())
    std = float(train_x.std())
    if abs(mean - float(meta["scaler_mean"])) > 1e-6:
        raise AssertionError(f"{dataset_name} scaler_mean mismatch: {mean} vs {meta['scaler_mean']}")
    if abs(std - float(meta["scaler_std"])) > 1e-6:
        raise AssertionError(f"{dataset_name} scaler_std mismatch: {std} vs {meta['scaler_std']}")
    return mean, std, meta


def split_ranges(meta):
    rows = []
    for split in ["train", "val", "test"]:
        info = meta["splits"][split]
        first = info["first_sample"]
        last = info["last_sample"]
        rows.append(
            {
                "split": split,
                "num_samples": info["num_samples"],
                "coverage": f"{first['input_start']}..{last['target_end']}",
            }
        )
    return rows


def florida_spot_check(dataset_name):
    panel_path = processed_dir(dataset_name) / "panel.csv"
    if not panel_path.exists() or not dataset_name.startswith("ili_"):
        return None
    panel = pd.read_csv(panel_path)
    florida = panel[(panel["state_name"] == "Florida") & (panel["is_imputed"] == 1)].head(12)
    if florida.empty:
        return None
    values = florida["weighted_ili"].round(5).tolist()
    sources = florida["imputation_source"].value_counts().to_dict()
    if len(set(values)) <= 1 and sources.get("linear_interpolate"):
        raise AssertionError(f"{dataset_name} Florida early imputation still looks like legacy interpolation")
    return {
        "first_epiweek": str(florida.iloc[0]["epiweek"]),
        "last_epiweek": str(florida.iloc[-1]["epiweek"]),
        "values": values,
        "sources": sources,
    }


def main():
    report_lines = [
        "# Leak-Free Dataset Check Report",
        "",
        "Generated by `check_leakfree_datasets.py`.",
        "",
    ]

    for dataset_name in DATASETS:
        root = package_dir(dataset_name)
        if not root.exists():
            raise FileNotFoundError(root)
        mean, std, meta = check_scaler(dataset_name)
        split_stats = [check_split(dataset_name, split) for split in ["train", "val", "test"]]
        spot = florida_spot_check(dataset_name)

        report_lines.extend(
            [
                f"## {dataset_name}",
                "",
                f"- imputation_policy: `{meta.get('imputation_policy', meta.get('missing_policy'))}`",
                f"- scaler_mean/std verified from train.x: `{mean:.8f}` / `{std:.8f}`",
                f"- missing_value_count: `{meta.get('missing_value_count', 'n/a')}`",
                "",
                "| Split | x shape | y shape | x_mask False | y_mask False | Coverage |",
                "|---|---:|---:|---:|---:|---|",
            ]
        )
        ranges = {row["split"]: row for row in split_ranges(meta)}
        for row in split_stats:
            coverage = ranges[row["split"]]["coverage"]
            report_lines.append(
                f"| {row['split']} | `{row['x_shape']}` | `{row['y_shape']}` | "
                f"{row['x_missing']} | {row['y_missing']} | {coverage} |"
            )
        if spot is not None:
            report_lines.extend(
                [
                    "",
                    "Florida early imputation spot check:",
                    f"- epiweeks: {spot['first_epiweek']}..{spot['last_epiweek']}",
                    f"- first values: `{spot['values']}`",
                    f"- sources: `{spot['sources']}`",
                ]
            )
        report_lines.append("")

    out_path = Path("review") / "leakfree_dataset_check_report.md"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(report_lines), encoding="utf-8")
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
